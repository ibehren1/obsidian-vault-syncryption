"""Render `docs/api.md`, the endpoint reference, from the app's OpenAPI schema.

`python -m syncryption_server apidocs > ../docs/api.md` writes it, and
`tests/test_apidocs.py` fails while the file in the repository is out of date. Only the
preamble below is written by hand; everything else comes from the schema, so the reference
can't drift from the routes and models.

What is in the schema is `/api/v1` and `/health`. The admin API, the home page and the
icons are deliberately left out of it (`include_in_schema=False`), so they are documented
in docs/protocol.md only.
"""

import json
from typing import Any

from syncryption_server import PROTOCOL_VERSION

PREAMBLE = f"""<!-- Generated by `python -m syncryption_server apidocs`. Do not edit. -->

# Vault Syncryption API reference

Every endpoint of the sync API, generated from the server's OpenAPI schema. It is protocol
version `{PROTOCOL_VERSION}`. [protocol.md](protocol.md) explains the flows this reference
only lists: the auth handshake, joining, pairing, conflicts, retention, limits and rate
limits, and the admin API. Crypto details are in [crypto.md](crypto.md).

- **Base URL:** the configured endpoint, e.g. `https://notes.example.com`.
- **Auth:** `Authorization: Bearer <token>` from `POST /api/v1/auth/verify` on every
  endpoint except `GET /health`, `POST /api/v1/auth/challenge` and
  `POST /api/v1/auth/verify`.
- **Bodies:** JSON, except blob uploads and downloads, which are raw bytes.
- **Binary values in JSON** are base64url without padding, and times are RFC 3339 UTC
  strings.
- **Errors:** every error answers with the [Error](#error) body. A body or parameter that
  fails validation gives `bad_request` with `details.fields` (locations and messages only,
  never the input). Each endpoint below lists the statuses the schema states; the full set
  of status and machine codes is in protocol.md 1.
- The admin API (`/admin`), the home page (`/`) and the icons are outside this reference
  and are documented in protocol.md 2 and 14.
"""

# Route groups are the schema's tags, in its order; routes without one come first.
UNTAGGED = "Server"
METHODS = ["get", "head", "post", "put", "delete"]


def render(schema: dict[str, Any]) -> str:
    """The whole of `docs/api.md` for an OpenAPI schema."""
    out = [PREAMBLE]
    groups: dict[str, list[str]] = {UNTAGGED: []}
    titles = {UNTAGGED: ""}
    for tag in schema.get("tags", []):
        groups[tag["name"]] = []
        titles[tag["name"]] = tag.get("description", "")
    for path, operations in schema["paths"].items():
        for method in METHODS:
            operation = operations.get(method)
            if operation is None:
                continue
            tag = next(iter(operation.get("tags", [])), UNTAGGED)
            groups.setdefault(tag, [])
            groups[tag].append(_operation(method, path, operation))
    out.append("## Endpoints\n")
    for tag, sections in groups.items():
        if not sections:
            continue
        out.append(f"### {tag.title() if tag != UNTAGGED else tag}\n")
        if titles.get(tag):
            out.append(f"{titles[tag]}\n")
        out += sections
    out.append("## Schemas\n")
    for name, model in sorted(schema.get("components", {}).get("schemas", {}).items()):
        out.append(_model(name, model))
    return "\n".join(out)


def _operation(method: str, path: str, operation: dict[str, Any]) -> str:
    lines = [f"#### `{method.upper()} {path}`\n"]
    description = operation.get("description", "").strip()
    if description:
        lines.append(" ".join(description.split()) + "\n")
    path_parameters = [p for p in operation.get("parameters", []) if p.get("in") == "path"]
    if path_parameters:
        lines.append("Path parameters:\n")
        # Path parameters are always required, so the column would say "yes" every time.
        lines.append(
            _table(["Name", "Type", "Notes"], [r[:2] + r[3:] for r in _parameters(path_parameters)])
        )
    query_parameters = [p for p in operation.get("parameters", []) if p.get("in") == "query"]
    if query_parameters:
        lines.append("Query parameters:\n")
        lines.append(_table(["Name", "Type", "Required", "Notes"], _parameters(query_parameters)))
    body = operation.get("requestBody")
    if body:
        required = "" if body.get("required", False) else " (optional)"
        lines.append(f"Request body{required}: {_content(body.get('content', {}))}\n")
    rows = []
    for status, response in sorted(operation.get("responses", {}).items()):
        note = response.get("description", "").strip()
        rows.append(
            [
                f"`{status}`",
                _content(response.get("content", {})) or "no body",
                "" if note == "Successful Response" else " ".join(note.split()),
            ]
        )
    lines.append(_table(["Status", "Body", "Notes"], rows))
    return "\n".join(lines)


def _parameters(parameters: list[dict[str, Any]]) -> list[list[str]]:
    rows = []
    for parameter in parameters:
        schema = parameter.get("schema", {})
        rows.append(
            [
                f"`{parameter['name']}`",
                _type(schema),
                "yes" if parameter.get("required", False) else "no",
                _notes(schema, parameter.get("description", "")),
            ]
        )
    return rows


def _model(name: str, model: dict[str, Any]) -> str:
    lines = [f"### {name}\n"]
    description = model.get("description", "").strip()
    if description:
        lines.append(" ".join(description.split()) + "\n")
    required = set(model.get("required", []))
    rows = []
    for field, schema in model.get("properties", {}).items():
        rows.append(
            [
                f"`{field}`",
                _type(schema),
                "yes" if field in required else "no",
                _notes(schema, schema.get("description", "")),
            ]
        )
    lines.append(_table(["Field", "Type", "Required", "Notes"], rows))
    return "\n".join(lines)


def _content(content: dict[str, Any]) -> str:
    """The media types of a body, with the model of a JSON one."""
    parts = []
    for media_type, body in content.items():
        if media_type == "application/octet-stream":
            parts.append(f"raw bytes (`{media_type}`)")
        else:
            parts.append(f"{_type(body.get('schema', {}))} (`{media_type}`)")
    return ", ".join(parts)


def _type(schema: dict[str, Any]) -> str:
    """One field's type, as markdown. References link to the schema's section."""
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return f"[{name}](#{name.lower()})"
    if "anyOf" in schema:
        return " \\| ".join(_type(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " \\| ".join(f"`{json.dumps(value)}`" for value in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        return _type(schema.get("items", {})) + "[]"
    if kind is None:
        return "`any`"
    return f"`{kind}`"


def _notes(schema: dict[str, Any], description: str) -> str:
    """One field's or parameter's description, then its default and bounds as a sentence."""
    limits = []
    if "default" in schema:
        limits.append(f"default `{json.dumps(schema['default'])}`")
    for low, high, unit in (
        ("minimum", "maximum", ""),
        ("minLength", "maxLength", " characters"),
        ("minItems", "maxItems", " items"),
    ):
        bounds = _bounds(schema, low, high, unit)
        if bounds:
            limits.append(bounds)
    text = " ".join(description.split())
    if text and limits and not text.endswith((".", "!", ":")):
        text += "."
    sentence = ", ".join(limits)
    if sentence:
        sentence = sentence[0].upper() + sentence[1:] + "."
    return f"{text} {sentence}".strip()


def _bounds(schema: dict[str, Any], low: str, high: str, unit: str) -> str:
    bottom, top = schema.get(low), schema.get(high)
    if bottom is not None and top is not None:
        return f"{_number(bottom)} to {_number(top)}{unit}"
    if bottom is not None:
        return f"at least {_number(bottom)}{unit}"
    if top is not None:
        return f"at most {_number(top)}{unit}"
    return ""


def _number(value: float) -> str:
    """JSON Schema writes numeric bounds as floats; whole ones read better as integers."""
    return str(int(value)) if float(value).is_integer() else str(value)


def _table(head: list[str], rows: list[list[str]]) -> str:
    if not rows:
        return ""
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(cell or "" for cell in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"
