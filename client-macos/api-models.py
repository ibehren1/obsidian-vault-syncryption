"""Regenerate Sources/SyncryptionAPI/Models.swift from the backend's OpenAPI schema.

    uv run --project ../backend --quiet python api-models.py          write the file
    uv run --project ../backend --quiet python api-models.py --check  fail if it is out of date

Each schema becomes a Codable struct. Fields that may be null or absent are optionals;
a required field that may be null (such as `parentRev`) is always encoded, as null.
"""

import json
import pathlib
import subprocess
import sys

OUT = pathlib.Path(__file__).parent / "Sources/SyncryptionAPI/Models.swift"
HEADER = "// Generated by api-models.py from the backend's OpenAPI schema. Do not edit.\n\nimport Foundation\n"

# Schema names that would shadow Swift types.
RENAMES = {"Error": "ErrorBody"}

KEYWORDS = {"default", "private", "public", "internal", "protocol", "class", "struct", "self", "Type"}


def swift_type(p: dict) -> tuple[str, bool]:
    """The Swift type of a property, and whether it may be null."""
    if "$ref" in p:
        name = p["$ref"].rsplit("/", 1)[-1]
        return RENAMES.get(name, name), False
    if "anyOf" in p:
        options = [o for o in p["anyOf"] if o.get("type") != "null"]
        nullable = len(options) != len(p["anyOf"])
        t, _ = swift_type(options[0])
        return t, nullable
    t = p.get("type")
    if t == "array":
        inner, _ = swift_type(p["items"])
        return f"[{inner}]", False
    if t == "string":
        return "String", False
    if t == "integer":
        return "Int", False
    if t == "boolean":
        return "Bool", False
    if t == "object":
        return "[String: JSONValue]", False
    raise SystemExit(f"unsupported schema: {p}")


def generate(schema: dict) -> str:
    out = [HEADER]
    for name, s in sorted(schema["components"]["schemas"].items()):
        props = s.get("properties", {})
        required = set(s.get("required", []))
        lines = []
        if s.get("description"):
            for d in s["description"].strip().splitlines():
                lines.append(f"/// {d}".rstrip())
        lines.append(f"public struct {RENAMES.get(name, name)}: Codable, Equatable, Sendable {{")
        fields = []
        for key in sorted(props):
            t, nullable = swift_type(props[key])
            optional = nullable or key not in required
            ident = f"`{key}`" if key in KEYWORDS else key
            fields.append((key, ident, t + ("?" if optional else ""), key in required))
            if props[key].get("description"):
                for d in props[key]["description"].strip().splitlines():
                    lines.append(f"    /// {d}".rstrip())
            lines.append(f"    public var {ident}: {t}{'?' if optional else ''}")
        params = ", ".join(f"{i}: {t}{' = nil' if t.endswith('?') else ''}" for _, i, t, _ in fields)
        lines.append("")
        lines.append(f"    public init({params}) {{")
        for _, i, _, _ in fields:
            lines.append(f"        self.{i} = {i}")
        lines.append("    }")
        if fields:
            lines.append("")
            lines.append("    private enum CodingKeys: String, CodingKey {")
            lines.append("        case " + ", ".join(i for _, i, _, _ in fields))
            lines.append("    }")
            lines.append("")
            lines.append("    public func encode(to encoder: any Encoder) throws {")
            lines.append("        var c = encoder.container(keyedBy: CodingKeys.self)")
            for _, i, t, req in fields:
                method = "encode" if req or not t.endswith("?") else "encodeIfPresent"
                lines.append(f"        try c.{method}({i}, forKey: .{i.strip('`')})")
            lines.append("    }")
        lines.append("}")
        out.append("\n".join(lines) + "\n")
    return "\n".join(out)


def main() -> None:
    schema = json.loads(
        subprocess.run([sys.executable, "-m", "syncryption_server", "openapi"], check=True, capture_output=True).stdout
    )
    text = generate(schema)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit(f"{OUT.name} is out of date: run api-models.py")
    else:
        OUT.write_text(text)


if __name__ == "__main__":
    main()
